/** Match only known generated messages; interpolated data is copied verbatim. */
export function translateCmsError(source: string): string | undefined {
  if (Object.hasOwn(cmsMessagesThai, source)) return cmsMessagesThai[source];
  let match = /^Route coordinates: line (\d+) needs latitude, longitude\.$/.exec(source);
  if (match) return `พิกัดเส้นทาง: บรรทัดที่ ${match[1]} ต้องระบุละติจูดและลองจิจูด คั่นด้วยเครื่องหมายจุลภาค (,)`;
  match = /^Route coordinates: line (\d+) is outside the valid range\.$/.exec(source);
  if (match) return `พิกัดเส้นทาง: ค่าพิกัดในบรรทัดที่ ${match[1]} อยู่นอกช่วงที่กำหนด`;
  match = /^The service is temporarily unavailable\. Your input has been kept; please try again\. Reference: ([\da-f-]+)$/.exec(source);
  if (match) return `ระบบไม่พร้อมใช้งานชั่วคราว ข้อมูลที่กรอกยังอยู่ กรุณาลองอีกครั้ง รหัสอ้างอิง: ${match[1]}`;
  match = /^“([\s\S]*)” has not been verified on the server\. Review or import it first\.$/.exec(source);
  if (match) return `ยังไม่ได้ยืนยันว่า “${match[1]}” ตรงกับข้อมูลบนเซิร์ฟเวอร์ กรุณาตรวจสอบหรือนำเข้าข้อมูลก่อน`;
  match = /^The local image “([\s\S]*)” has not been verified in the media library\.$/.exec(source);
  if (match) return `ยังไม่ได้ยืนยันว่ารูปภาพ “${match[1]}” จากเบราว์เซอร์ถูกบันทึกไว้ในคลังรูปภาพแล้ว`;
  match = /^Too (small|big): (?:expected )?(string|number|array) (?:to have|to be|to contain) ([<>]=?)([+-]?\d+(?:\.\d+)?)(?: characters| items)?$/.exec(source);
  if (match) {
    const [, size, kind, operator, limit] = match;
    const boundary = size === 'small' ? (operator === '>' ? 'มากกว่า' : 'อย่างน้อย') : (operator === '<' ? 'น้อยกว่า' : 'ไม่เกิน');
    return kind === 'string' ? `กรอกข้อความยาว${boundary} ${limit} ตัวอักษร` : kind === 'array' ? `ระบุ${boundary} ${limit} รายการ` : `กรอกค่า${boundary} ${limit}`;
  }
  if (/^Invalid input: expected (?:string|number|int|array|object|boolean), received (?:undefined|null|string|number|NaN|array|object|boolean)$/.test(source)) return 'กรอกข้อมูลให้ถูกต้องและครบถ้วน';
  if (/^Invalid (?:option: expected one of|input: expected) /.test(source)) return 'เลือกค่าที่ถูกต้อง';
  const fields = [...source.matchAll(validationPrefix)];
  if (fields.length && fields[0].index === 0) {
    const translated: string[] = [];
    for (let index = 0; index < fields.length; index++) {
      const field = fields[index];
      const issue = source.slice(field.index + field[0].length, fields[index + 1]?.index ?? source.length);
      const message = translateCmsError(issue);
      if (!message) return undefined;
      translated.push(`${validationFieldsThai[field[1]]}: ${message}`);
    }
    return translated.join(' ');
  }
  return undefined;
}
