import 'server-only';
import { randomUUID } from 'node:crypto';
import type { Filter } from 'mongodb';
import type { z } from 'zod';
import type { Enquiry } from '@/lib/cms-types';
import { escapeInboxSearch, type EnquiryPage, type InboxFilters, type InboxQuery } from '@/lib/inbox-query';
import { collections, ensureIndexes, getDb, type EnquiryDocument } from './db';
import { digest, rateLimit } from './auth';
import { HttpError } from './http';
import { enquirySchema, inboxSchema } from './validation';
import { nextCursor, readCursor } from './pagination';
import { initialNotification, notificationView } from './enquiry-notifications';

export function cleanEnquiry(record: EnquiryDocument): Enquiry {
  const { _id, submissionId, fingerprint, consentAt, notificationDelivery, ...value } = record;
  void _id; void submissionId; void fingerprint; void consentAt; void notificationDelivery;
  return { ...value, notification: notificationView(record) };
}
export async function submitEnquiry(input: z.infer<typeof enquirySchema>) {
  await ensureIndexes();
  const c = collections(await getDb());
  const { submissionId, website, consent, ...fields } = input;
  void website; void consent;
  const fingerprint = digest(JSON.stringify(fields));
  const prior = await c.enquiries.findOne({ submissionId });
  if (prior) {
    if (prior.fingerprint !== fingerprint) throw new HttpError(409, 'The previous submission differs. Refresh before sending another enquiry.');
    return { id: prior.id };
  }
  await rateLimit(`contact:${fields.email}`, 5, 60 * 60);
  await rateLimit('contact:global', 100, 60 * 60);
  const now = new Date().toISOString();
  const id = randomUUID();
  try { await c.enquiries.insertOne({ _id: id, id, ...fields, submissionId, fingerprint, status: 'New', createdAt: now, updatedAt: now, revision: 1, consentAt: now, notification: initialNotification() }); }
  catch (error) {
    if ((error as { code?: number }).code !== 11000) throw error;
    const existing = await c.enquiries.findOne({ submissionId });
    if (!existing || existing.fingerprint !== fingerprint) throw new HttpError(409, 'This submission was already used. Please start a new enquiry.');
    return { id: existing.id };
  }
  return { id };
}
export async function getEnquiries() {
  return (await collections(await getDb()).enquiries.find().sort({ createdAt: -1 }).toArray()).map(cleanEnquiry);
}
export async function getEnquiry(id: string) {
  const record = await collections(await getDb()).enquiries.findOne({ _id: id });
  if (!record) throw new HttpError(404, 'This enquiry is no longer available. Refresh the inbox.');
  return cleanEnquiry(record);
}
export function readEnquiryCursor(rawCursor: string | null) {
  const cursor = readCursor(rawCursor);
  // Cursors are opaque tokens generated by nextCursor; reject extra fields and permissive base64 decoding.
  if (rawCursor !== null && (!cursor || nextCursor(cursor) !== rawCursor)) throw new HttpError(400, 'This page cursor is invalid. Refresh the list.');
  return cursor;
}

export function buildEnquiryFilter(filters: InboxFilters, cursor: ReturnType<typeof readEnquiryCursor> = null): Filter<EnquiryDocument> {
  const match: Filter<EnquiryDocument> = {};
  if (filters.status !== 'All') match.status = filters.status;
  if (filters.q) {
    const literal = escapeInboxSearch(filters.q);
    match.$or = ['name', 'email', 'company', 'subject', 'message', 'id'].map(field => ({ [field]: { $regex: literal, $options: 'i' } }));
  }
  if (!cursor) return match;
  return { $and: [match, { $or: [{ createdAt: { $lt: cursor.createdAt } }, { createdAt: cursor.createdAt, _id: { $lt: cursor.id } }] }] };
}

export async function getEnquiryPage(query: InboxQuery): Promise<EnquiryPage> {
  const cursor = readEnquiryCursor(query.cursor);
  const match = buildEnquiryFilter(query);
  const pageFilter = buildEnquiryFilter(query, cursor);
  await ensureIndexes();
  const enquiries = collections(await getDb()).enquiries;
  const totalAllResult = enquiries.countDocuments({}, { hint: '_id_' });
  const newCountResult = enquiries.countDocuments({ status: 'New' });
  const totalResult = !query.q && query.status === 'All' ? totalAllResult
    : !query.q && query.status === 'New' ? newCountResult : enquiries.countDocuments(match);
  const [items, total, totalAll, newCount] = await Promise.all([
    enquiries.find(pageFilter).sort({ createdAt: -1, _id: -1 }).limit(51).toArray(),
    totalResult, totalAllResult, newCountResult,
  ]);
  return { enquiries: items.slice(0, 50).map(cleanEnquiry), nextCursor: items.length > 50 ? nextCursor(items[49]) : null, total, totalAll, newCount };
}
export async function updateEnquiry(input: z.infer<typeof inboxSchema>) {
  const result = await collections(await getDb()).enquiries.findOneAndUpdate({ _id: input.id, revision: input.expectedRevision }, { $set: { status: input.status, updatedAt: new Date().toISOString() }, $inc: { revision: 1 } }, { returnDocument: 'after' });
  if (!result) throw new HttpError(409, 'This enquiry changed elsewhere. Refresh and try again.');
  return cleanEnquiry(result);
}
